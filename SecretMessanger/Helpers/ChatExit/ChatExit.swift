import Foundation

//MARK: Из группы уходят двумя способами, и для слушателей переписки они неотличимы:
// правила отказывают одинаково — по составу, в котором тебя больше нет. Без отметки
// вышедший по своей воле получал бы вдогонку «вас удалили из группы», хотя удалял
// себя сам и уже подтвердил это в диалоге выхода.
//
// Отметку ставит выход, снимает первый же отказ, и живёт она ровно до него: если
// создатель вернёт человека обратно, а потом удалит по-настоящему, сообщение придёт
// как положено.
enum ChatExit {

    private static var voluntary: Set<String> = []

    static func mark(_ convoId: String) {
        voluntary.insert(convoId)
    }

    //MARK: Проверка отметку и снимает — двух отказов по одному поводу не бывает, а
    // застрявшая отметка молча съела бы следующее удаление.
    static func wasVoluntary(_ convoId: String) -> Bool {
        voluntary.remove(convoId) != nil
    }

    //MARK: Диалог открылся, значит доступ есть — отметка от прошлого выхода больше
    // ничего не описывает. Сюда же приходит неудавшийся выход: запись не прошла,
    // человек остался в группе.
    static func forget(_ convoId: String) {
        voluntary.remove(convoId)
    }
}
