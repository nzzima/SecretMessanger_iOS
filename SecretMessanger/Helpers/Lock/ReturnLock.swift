import Foundation

//MARK: Запирать ли приложение на возврате — решение из двух величин: где мы были и
// сколько отсутствовали. Логика вынесена сюда, потому что внутри `SceneDelegate` её
// проверить нечем: там окна, сцены и системные события, а здесь два числа и правило.
/// Нужно ли спросить биометрию снова, когда приложение вернулось на экран.
enum ReturnLock {

    //MARK: Без порога Face ID срабатывал бы на каждое переключение — сходить в браузер
    // за ссылкой, ответить на звонок, посмотреть код из СМС. Приложение, которое
    // переспрашивает по десять раз на дню, выключают целиком, и защиты от него остаётся
    // ноль. Минута — это «отвлёкся», а не «ушёл».
    //
    // Порог **не** относится к заслонке поверх окна: та ставится всегда и сразу, потому
    // что снимок для переключателя задач система делает независимо от того, вернёмся мы
    // через секунду или через час.
    /// Сколько можно отсутствовать, чтобы не переспрашивать.
    static let grace: TimeInterval = 60

    /// Запирать ли приложение.
    ///
    /// - Parameters:
    ///   - state: какое окно было открыто, когда уходили. Запирать имеет смысл только
    ///     рабочее: на экране блокировки и на входе запирать нечего, а лишний переход
    ///     сбросил бы наполовину введённый пароль.
    ///   - leftAt: когда ушли в фон; `nil` — не уходили вовсе.
    static func shouldLock(state: WindowManager, leftAt: Date?, now: Date = Date()) -> Bool {
        guard state == .appWindow, let leftAt else { return false }

        //MARK: Отрицательная разница — часы перевели назад, пока нас не было. Ушли мы
        // при этом на неизвестный срок, и считать это «отвлёкся на секунду» нельзя:
        // безопаснее переспросить.
        let away = now.timeIntervalSince(leftAt)

        return away < 0 || away > grace
    }
}
